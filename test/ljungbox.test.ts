test("Ljung-Box vs statsmodels reference (AR(1), n=64)", () => {
  const r5 = ljungBox(AR1, 5);
  close(r5.statistic, 29.44703410541104);
  close(r5.pValue, 1.894487476786188e-5, 1e-12);
  assert.equal(r5.degreesOfFreedom, 5);

  const r10 = ljungBox(AR1, 10);
  close(r10.statistic, 39.600816577561616);
  close(r10.pValue, 1.9918226202030487e-5, 1e-12);

  const r20 = ljungBox(AR1, 20);
  close(r20.statistic, 51.926341744914986);
  close(r20.pValue, 0.00011670815747718229, 1e-12);
});

test("Box-Pierce vs statsmodels reference (AR(1), n=64)", () => {
  const r5 = boxPierce(AR1, 5);
  close(r5.statistic, 27.55391271183425);
  close(r5.pValue, 4.4485167175334426e-5, 1e-12);

  const r10 = boxPierce(AR1, 10);
  close(r10.statistic, 36.2013300201597);
  close(r10.pValue, 7.772613585065212e-5, 1e-12);

  const r20 = boxPierce(AR1, 20);
  close(r20.statistic, 44.88334477659736);
  close(r20.pValue, 0.0011443712981785488, 1e-12);
});

test("Box-Pierce statistic never exceeds Ljung-Box (same series/lags)", () => {
  for (const h of [3, 7, 15]) {
    assert.ok(boxPierce(AR1, h).statistic <= ljungBox(AR1, h).statistic + 1e-12);
  }
});

test("fittedParams reduces the degrees of freedom", () => {
  const raw = ljungBox(AR1, 10);
  const resid = ljungBox(AR1, 10, 2); // e.g. ARMA(1,1) residual
  assert.equal(resid.degreesOfFreedom, 8);
  close(resid.statistic, raw.statistic); // same Q, different reference df
  assert.ok(resid.pValue < raw.pValue); // fewer df => same Q is more extreme
});

