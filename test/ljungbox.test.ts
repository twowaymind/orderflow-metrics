test("chiSquareSurvival matches scipy.stats.chi2.sf across degrees of freedom", () => {
  close(chiSquareSurvival(3.5, 5), 0.6233876277495822, 1e-12);
  close(chiSquareSurvival(18.2, 10), 0.0516821935539136, 1e-12);
  close(chiSquareSurvival(25.0, 20), 0.20143110494553594, 1e-12);
  close(chiSquareSurvival(2.0, 1), 0.15729920705028105, 1e-12);
  close(chiSquareSurvival(4.0, 2), 0.1353352832366127, 1e-12);
  close(chiSquareSurvival(50.0, 7), 1.4444852779215402e-8, 1e-16);
  close(chiSquareSurvival(200.0, 20), 1.125347396084281e-31, 1e-40);
  assert.equal(chiSquareSurvival(0, 5), 1);
  assert.equal(chiSquareSurvival(-1, 5), 1);
  assert.ok(Number.isNaN(chiSquareSurvival(5, 0)));
});

test("edge cases return NaN", () => {
  assert.ok(Number.isNaN(ljungBox([1, 2, 3], 5).statistic)); // series too short
  assert.ok(Number.isNaN(ljungBox(AR1, 0).statistic)); // lags < 1
  assert.ok(Number.isNaN(ljungBox(new Array(20).fill(7), 5).statistic)); // constant
  assert.ok(Number.isNaN(ljungBox(AR1, 3, 3).statistic)); // df < 1
});
