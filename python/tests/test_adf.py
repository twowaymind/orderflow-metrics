def test_random_walk_c_lag0():
    r = augmented_dickey_fuller(RW, 0, "c")
    assert math.isclose(r.statistic, -2.331900559352451, abs_tol=1e-8)
    assert math.isclose(r.p_value, 0.16188568525797642, abs_tol=1e-6)
    assert r.used_lag == 0
    assert r.nobs == 79
    assert math.isclose(r.critical_values["1%"], -3.5159766913976376, abs_tol=1e-9)
    assert math.isclose(r.critical_values["5%"], -2.898885703483903, abs_tol=1e-9)
    assert math.isclose(r.critical_values["10%"], -2.5866935058484217, abs_tol=1e-9)
    assert r.p_value > 0.05  # fail to reject: not stationary


