def test_stationary_ar_c_lag0():
    r = augmented_dickey_fuller(AR, 0, "c")
    assert math.isclose(r.statistic, -4.347242504008066, abs_tol=1e-8)
    assert math.isclose(r.p_value, 0.00036758119431389897, abs_tol=1e-6)
    assert r.p_value < 0.01  # reject: stationary / mean-reverting
    assert r.statistic < r.critical_values["1%"]


