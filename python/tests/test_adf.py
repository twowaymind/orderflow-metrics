def test_edge_cases():
    assert math.isnan(augmented_dickey_fuller(RW, -1).statistic)  # negative lags
    assert math.isnan(augmented_dickey_fuller([1, 2, 3], 0).statistic)  # too short
    assert math.isnan(augmented_dickey_fuller(RW, 0, "x").statistic)  # bad spec
    assert math.isnan(augmented_dickey_fuller([5.0] * 40, 0).statistic)  # constant → singular
